// Precompiles the theme-file JSON schema into plain code. The app's CSP has no
// 'unsafe-eval', and Ajv's runtime compile() builds functions from strings, so
// it would fail in the installed app (white screen). Run after changing
// src/theme/themes/samix-theme.schema.json; a test fails when the output is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const schema = JSON.parse(readFileSync(`${root}src/theme/themes/samix-theme.schema.json`, 'utf8'));

export const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  let value;
  while (pos < len) {
    length++;
    value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}`;

export function generate() {
  const ajv = new Ajv2020({ allErrors: true, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  const code = standaloneCode(ajv, validate);
  // The only helper the output pulls in is Ajv's CJS ucs2length (string length
  // in code points, for maxLength). `require` does not exist in the WebView, so
  // it is inlined; the test compares it with Ajv's own.
  const call = 'require("ajv/dist/runtime/ucs2length").default';
  if (code.split(call).length - 1 !== 1 || /require\(/.test(code.replace(call, ''))) {
    throw new Error('unexpected runtime helpers in the generated validator');
  }
  return (
    '// GENERATED by scripts/build-theme-validator.mjs — do not edit.\n// @ts-nocheck\n' +
    `${UCS2LENGTH}\n` +
    code.replace(call, 'ucs2length')
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(`${root}src/theme/validateTheme.generated.js`, generate());
  console.log('wrote src/theme/validateTheme.generated.js');
}
